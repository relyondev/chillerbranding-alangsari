parsed AS (
  SELECT
    upper(trim(full_code)) AS full_code,
    split_part(upper(trim(full_code)),'/',1)||'/'||split_part(upper(trim(full_code)),'/',2) AS stockpoint_code,
    split_part(upper(trim(full_code)),'/',3) AS suffix,
    upper(trim(salesman_name)) AS salesman_name
  FROM seed
),
eligible AS (
  SELECT *
  FROM parsed
  WHERE suffix ~ '^S\d{1,5}$'
    AND salesman_name <> 'VACANT'
),
matched AS (
  SELECT e.*, sp.id AS stockpoint_id
  FROM eligible e
  JOIN public.stockpoints sp
    ON sp.code = e.stockpoint_code
   AND sp.is_active = true
),
inserted AS (
  INSERT INTO public.salesmen(
    stockpoint_id, suffix, full_code, name, name_normalized, created_by, updated_by
  )
  SELECT
    m.stockpoint_id,
    m.suffix,
    m.full_code,
    m.salesman_name,
    public.normalize_business_text(m.salesman_name),
    NULL,
    NULL
  FROM matched m
  ON CONFLICT (stockpoint_id, suffix) WHERE is_active = true
  DO NOTHING
  RETURNING id
),
missing_prefixes AS (
  SELECT split_part(e.stockpoint_code,'/',1) AS stockpoint_prefix, count(*) AS row_count
  FROM eligible e
  LEFT JOIN public.stockpoints sp
    ON sp.code = e.stockpoint_code
   AND sp.is_active = true
  WHERE sp.id IS NULL
  GROUP BY 1
)
SELECT
  (SELECT count(*) FROM seed) AS source_rows,
  (SELECT count(*) FROM parsed WHERE suffix = 'SX00') AS skipped_sx00,
  (SELECT count(*) FROM parsed WHERE salesman_name = 'VACANT') AS skipped_vacant,
  (SELECT count(*) FROM matched) AS eligible_on_current_stockpoints,
  (SELECT count(*) FROM inserted) AS inserted_now,
  (SELECT count(*) FROM eligible e LEFT JOIN public.stockpoints sp ON sp.code=e.stockpoint_code AND sp.is_active=true WHERE sp.id IS NULL) AS skipped_missing_stockpoint,
  COALESCE((SELECT jsonb_object_agg(stockpoint_prefix, row_count ORDER BY stockpoint_prefix) FROM missing_prefixes), '{}'::jsonb) AS missing_by_prefix;

